-- Annual rainfall classification (CHIRPS climatology 2015-2024).
--
-- These are annual mean values, NOT monthly values. Classes 1-5 follow the
-- approved labels: 1 Sangat Rendah, 2 Rendah, 3 Sedang, 4 Tinggi,
-- 5 Sangat Tinggi.
--
-- Districts without CHIRPS coverage keep kelas_hujan and label_hujan NULL.
-- Do not coerce them to 0 or to a class.

CREATE TABLE IF NOT EXISTS core.district_rainfall_classification (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id  integer NOT NULL UNIQUE REFERENCES core.districts(id),
    n_piksel     integer CHECK (n_piksel >= 0),
    mean_hujan_mm double precision CHECK (mean_hujan_mm >= 0),
    kelas_hujan  smallint CHECK (kelas_hujan BETWEEN 1 AND 5),
    label_hujan  text
);

CREATE TABLE IF NOT EXISTS core.regency_rainfall_classification (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regency_id    bigint NOT NULL UNIQUE REFERENCES core.regency(id),
    n_kec         integer CHECK (n_kec >= 0),
    n_kec_berdata integer CHECK (n_kec_berdata >= 0),
    mean_hujan_mm double precision CHECK (mean_hujan_mm >= 0),
    min_kec_mm    double precision CHECK (min_kec_mm >= 0),
    maks_kec_mm   double precision CHECK (maks_kec_mm >= 0),
    kelas_hujan   smallint CHECK (kelas_hujan BETWEEN 1 AND 5),
    label_hujan   text
);
