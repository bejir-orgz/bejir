-- Monthly rainfall per district (CHIRPS v3.0, ~5.5 km resolution).
--
-- year IS NULL marks a climatology aggregate (for example the 2015-2024 mean).
-- Per-year records fill year with an actual calendar year.
--
-- hujan_mm MUST stay NULL for districts without CHIRPS coverage (the 7
-- districts in Bekasi). Do not coerce missing values to 0.

CREATE TABLE IF NOT EXISTS core.district_rainfall_monthly (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id integer NOT NULL REFERENCES core.districts(id),
    year        integer,
    month       integer NOT NULL CHECK (month BETWEEN 1 AND 12),
    -- Total pixels of the district (statistik_kecamatan.csv). Never the
    -- CHIRPS rain-mask count.
    n_piksel       integer CHECK (n_piksel >= 0),
    -- Pixels with a valid CHIRPS value; 0 for districts without coverage.
    -- Used only to weight rainfall aggregation.
    n_piksel_hujan integer CHECK (n_piksel_hujan >= 0),
    hujan_mm    double precision CHECK (hujan_mm >= 0)
);

-- COALESCE keeps climatology rows (year IS NULL) unique as well; a plain
-- UNIQUE constraint treats NULLs as distinct and would allow duplicates.
CREATE UNIQUE INDEX IF NOT EXISTS ux_district_rainfall_monthly_unique
    ON core.district_rainfall_monthly (district_id, COALESCE(year, -1), month);

CREATE INDEX IF NOT EXISTS ix_district_rainfall_monthly_district_id
    ON core.district_rainfall_monthly (district_id);

CREATE INDEX IF NOT EXISTS ix_district_rainfall_monthly_year
    ON core.district_rainfall_monthly (year);
